fprintf(fptr, " * @param extra_data_size size of extra_data in bytes, if extra_data size=0 the optional data is not uploaded\n");
fprintf(fptr, " * @param extra_data optional set of data uploaded by load_extra_data()\n");
fprintf(fptr, " * @return 0 if entry has been added successfuly, otherwise return error code. If nonzero value is returned the main code will terminate.\n");
fprintf(fptr, " * \n");
